"""Cryptographic message signing and canonical serialization for NammaFlow devices."""

import hmac
import hashlib
import json
from typing import Any, Dict, Union


def canonicalize(data: Union[Dict[str, Any], list, str, int, float, bool]) -> bytes:
    """Produces a deterministic, canonical JSON byte representation.
    
    Keys are sorted recursively and compact separators (no extraneous spaces)
    are used so that signatures generated by ESP32, Python, or Web clients match.
    """
    return json.dumps(data, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode('utf-8')


def sign_message(secret_key: str, data: Any) -> str:
    """Signs canonical data using HMAC-SHA256 and returns a hex string."""
    key_bytes = secret_key.encode('utf-8')
    payload_bytes = canonicalize(data)
    h = hmac.new(key_bytes, payload_bytes, hashlib.sha256)
    return h.hexdigest()


def verify_signature(secret_key: str, data: Any, signature_hex: str) -> bool:
    """Verifies HMAC-SHA256 signature in constant time against timing attacks."""
    if not signature_hex or not secret_key:
        return False
    expected_sig = sign_message(secret_key, data)
    return hmac.compare_digest(expected_sig.lower(), signature_hex.lower())
